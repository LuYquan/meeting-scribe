import type { EmailDraft, MeetingRecord, SynthesisResult } from "./types";

function formatDate(iso: string): string {
  const d = new Date(iso);
  return Number.isNaN(d.getTime()) ? iso : d.toLocaleString();
}

export function meetingToMarkdown(record: MeetingRecord): string {
  const r = record.result;
  const lines: string[] = [
    `# ${r.title}`,
    "",
    `Analyzed ${formatDate(record.createdAt)} · Inference: ${record.source === "on_device" ? "On-device (Gemini Nano)" : "Cloud (Gemini)"} · ${record.latencyMs} ms`,
    "",
    "## Summary",
    "",
    r.summary || "_No summary._",
    "",
  ];
  if (r.participants.length > 0) {
    lines.push("## Participants", "", r.participants.map((p) => `- ${p}`).join("\n"), "");
  }
  if (r.keyPoints.length > 0) {
    lines.push("## Key points", "", r.keyPoints.map((k) => `- ${k}`).join("\n"), "");
  }
  lines.push(
    "## Action items",
    "",
    r.actionItems.length > 0
      ? r.actionItems
          .map(
            (a) =>
              `- [ ] ${a.task}${a.owner ? ` — ${a.owner}` : ""}${a.dueDate ? ` (due ${a.dueDate})` : ""}${a.priority ? ` [${a.priority}]` : ""}`,
          )
          .join("\n")
      : "_None recorded._",
    "",
  );
  lines.push(
    "## Decisions",
    "",
    r.decisions.length > 0
      ? r.decisions.map((d) => `- ${d.decision}${d.context ? ` — ${d.context}` : ""}`).join("\n")
      : "_None recorded._",
    "",
  );
  lines.push("---", "", "_Generated by Meeting Scribe with Firebase AI Logic hybrid inference._", "");
  return lines.join("\n");
}

export function emailToMarkdown(draft: EmailDraft): string {
  return `Subject: ${draft.subject}\n\n${draft.body}\n`;
}

/** Action items as a Markdown checklist, ready to paste into Notion/Linear/Slack. */
export function actionItemsToMarkdown(
  items: MeetingRecord["result"]["actionItems"],
): string {
  if (items.length === 0) return "";
  return items
    .map(
      (a) =>
        `- [ ] ${a.task}${a.owner ? ` (@${a.owner})` : ""}${a.dueDate ? ` (due ${a.dueDate})` : ""}${a.priority ? ` [${a.priority}]` : ""}`,
    )
    .join("\n");
}

/** Decisions as a Markdown list. */
export function decisionsToMarkdown(
  decisions: MeetingRecord["result"]["decisions"],
): string {
  if (decisions.length === 0) return "";
  return decisions
    .map((d) => `- ${d.decision}${d.context ? ` — ${d.context}` : ""}`)
    .join("\n");
}

/** Key points as a Markdown bullet list. */
export function keyPointsToMarkdown(points: string[]): string {
  if (points.length === 0) return "";
  return points.map((k) => `- ${k}`).join("\n");
}

/** Participants as a comma-separated list. */
export function participantsToText(participants: string[]): string {
  return participants.join(", ");
}

/** Everything the user has — meetings plus the latest synthesis — as one JSON backup. */
export function exportAllJson(
  meetings: MeetingRecord[],
  synthesis: import("./types").SynthesisRecord | null,
): string {
  return JSON.stringify(
    {
      app: "meeting-scribe",
      exportedAt: new Date().toISOString(),
      meetings,
      synthesis,
    },
    null,
    2,
  );
}

export function synthesisToMarkdown(
  synthesis: SynthesisResult,
  meetingTitles: string[],
): string {
  const lines: string[] = [
    "# Cross-meeting synthesis",
    "",
    `Across: ${meetingTitles.join("; ")}`,
    "",
    "## Recurring themes",
    "",
  ];
  if (synthesis.themes.length === 0) lines.push("_No recurring themes found._", "");
  for (const t of synthesis.themes) {
    lines.push(
      `### ${t.theme}`,
      "",
      t.evidence,
      "",
      t.meetings.length > 0 ? `Seen in: ${t.meetings.join(", ")}` : "",
      "",
    );
  }
  lines.push(
    "## Recurring action items",
    "",
    synthesis.recurringActions.length > 0
      ? synthesis.recurringActions
          .map((a) => `- [ ] ${a.task}${a.owner ? ` — ${a.owner}` : ""}`)
          .join("\n")
      : "_None._",
    "",
    "## Open questions",
    "",
    synthesis.openQuestions.length > 0
      ? synthesis.openQuestions.map((q) => `- ${q}`).join("\n")
      : "_None._",
    "",
  );
  return lines.join("\n");
}

export async function copyText(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    return false;
  }
}

export function downloadText(filename: string, text: string): void {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
